def calculate_accuracy(
    logits,
    labels,
    indices
):
    predictions = (
        logits[indices]
        .argmax(dim=1)
    )

    correct = (
        predictions
        == labels[indices]
    ).sum().item()

    return correct / len(indices)

def train_model(
    model,
    model_name,
    learning_rate=0.01,
    weight_decay=5e-4,
    epochs=200,
    patience=30,
    verbose=True
):

    model = model.to(device)

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=learning_rate,
        weight_decay=weight_decay
    )

    best_val_acc = -1.0
    best_epoch = 0
    best_state = None

    patience_counter = 0

    history = {
        "epoch": [],
        "loss": [],
        "train_acc": [],
        "val_acc": []
    }

    for epoch in range(1, epochs + 1):


        # Training

        model.train()

        optimizer.zero_grad()

        logits = model(
            X_device,
            edge_index_device
        )

        loss = criterion(
            logits[train_idx_device],
            y_device[train_idx_device]
        )

        loss.backward()

        optimizer.step()


        # Validation

        model.eval()

        with torch.no_grad():

            eval_logits = model(
                X_device,
                edge_index_device
            )

            train_acc = calculate_accuracy(
                eval_logits,
                y_device,
                train_idx_device
            )

            val_acc = calculate_accuracy(
                eval_logits,
                y_device,
                valid_idx_device
            )

        # Save history
        history["epoch"].append(epoch)
        history["loss"].append(
            loss.item()
        )
        history["train_acc"].append(
            train_acc
        )
        history["val_acc"].append(
            val_acc
        )


        # Best model tracking

        if val_acc > best_val_acc:

            best_val_acc = val_acc
            best_epoch = epoch

            best_state = copy.deepcopy(
                model.state_dict()
            )

            patience_counter = 0

        else:
            patience_counter += 1


        # Training log

        if verbose and (
            epoch == 1
            or epoch % 10 == 0
        ):

            print(
                f"{model_name} | "
                f"Epoch {epoch:03d} | "
                f"Loss: {loss.item():.4f} | "
                f"Train Acc: {train_acc:.4f} | "
                f"Val Acc: {val_acc:.4f}"
            )


        # Early stopping

        if patience_counter >= patience:

            if verbose:
                print(
                    f"\nEarly stopping at "
                    f"epoch {epoch}."
                )

            break

    # Restore best validation model
    model.load_state_dict(
        best_state
    )

    history = pd.DataFrame(
        history
    )

    if verbose:

        print(
            f"\nBest {model_name} "
            f"Validation Accuracy: "
            f"{best_val_acc:.4f}"
        )

        print(
            "Best Epoch:",
            best_epoch
        )

    return (
        model,
        history,
        best_val_acc,
        best_epoch
    )

